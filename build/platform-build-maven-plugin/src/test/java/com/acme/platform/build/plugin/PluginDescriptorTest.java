package com.acme.platform.build.plugin;

import static org.assertj.core.api.Assertions.assertThat;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import org.junit.jupiter.api.Test;

/**
 * Verifies goal + parameter wiring via the descriptor maven-plugin-plugin generates at
 * process-classes (in lieu of a full nested-reactor integration test; see decision D3).
 */
class PluginDescriptorTest {

    @Test
    void descriptorDeclaresBothGoalsWithTheirParameters() throws IOException {
        String descriptor;
        try (InputStream in = PluginDescriptorTest.class.getResourceAsStream("/META-INF/maven/plugin.xml")) {
            assertThat(in).as("plugin.xml generated by maven-plugin-plugin").isNotNull();
            descriptor = new String(in.readAllBytes(), StandardCharsets.UTF_8);
        }

        assertThat(descriptor)
                .contains("<goal>new-module</goal>")
                .contains("<goal>check-bom</goal>")
                .contains("<name>capability</name>")
                .contains("<name>kind</name>")
                .contains("<name>provider</name>")
                .contains("${maven.multiModuleProjectDirectory}")
                .contains("${reactorProjects}");
    }
}
