-- Consumer migration for the hardening phase-03 harness (runs as the schema owner, 19c-safe). The
-- constraint names are distinctive so the scenario can assert they never reach a response body.
-- Grants go to the role the runtime user holds (docs/modules/data.md, Schema owner and runtime user).
create table hh_consignor (
    id      numeric(19) primary key,
    hh_name varchar(100) not null
);

insert into hh_consignor (id, hh_name) values (1, 'first consignor');

create table hh_parcel (
    id              numeric(19) generated by default as identity primary key,
    hh_ref_code     varchar(64),
    hh_weight       numeric(10),
    hh_label        varchar(100) not null,
    hh_consignor_id numeric(19),
    constraint hh_uq_parcel_ref unique (hh_ref_code),
    constraint hh_ck_parcel_weight check (hh_weight > 0),
    constraint hh_fk_parcel_consignor foreign key (hh_consignor_id) references hh_consignor (id)
);

grant select on hh_consignor to hh_rw;
grant select, insert, update, delete on hh_parcel to hh_rw;
grant select, insert, update, delete on note to hh_rw;
